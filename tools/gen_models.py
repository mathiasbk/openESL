#!/usr/bin/env python3
"""
Generates the code that lists the tag models from the registry, shared/models.json:

  shared/models_gen.h          ESL_MODEL_* codes, screen sizes, ESL_MODEL_COUNT and ESL_MODEL_LIST
                               (AP, simulator, tag and web renderer, through shared/proto.h)
  tag/src/model_gen.h          MODEL_CODE, MODEL_NAME, DRAW_W/H, MODEL_HAS_RED for -DMODEL=<build>
  web/js/models.js             the models for the web page
  tools/esl-client/esl_client.py   the block between "BEGIN models" and "END models" (the client
                               is a single file people copy, so it carries its own copy)

The Python tools in the repository (tag/tools/build.py, web/build.py, tools/flash-tui) read
shared/models.json directly through shared/models.py.

  python tools/gen_models.py           write the files
  python tools/gen_models.py --check   fail if a file is not what the registry gives (CI, check.py)

The generated files are checked in, so nothing else needs this script to build.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "shared"))
import models  # noqa: E402

HEADER = "Generated by tools/gen_models.py from shared/models.json. Do not edit; run the script."
CHIPS = ("zbs243",)
COLORS = ("black", "white", "red", "yellow")
STATUSES = ("supported", "experimental", "planned")
FIELDS = ("code", "build", "name", "id", "label", "product", "chip", "radio", "width", "height",
          "colors", "mac_code", "status")


def validate(ms):
    errors = []
    for i, m in enumerate(ms):
        where = "model %s" % m.get("id", i)
        for f in FIELDS:
            if f not in m:
                errors.append("%s: no %s" % (where, f))
        if errors:
            continue
        if not re.fullmatch(r"[0-9]+", m["build"]):
            errors.append("%s: build must be digits (it is -DMODEL=<build> and ESL_MODEL_<build>)" % where)
        if not re.fullmatch(r"[a-z0-9-]+", m["id"]):
            errors.append("%s: id must be lower case letters, digits and -" % where)
        if m["chip"] not in CHIPS:
            errors.append("%s: chip %s is not one the tag firmware is built for (%s)" % (where, m["chip"], CHIPS))
        if m["status"] not in STATUSES:
            errors.append("%s: status must be one of %s" % (where, STATUSES))
        if any(c not in COLORS for c in m["colors"]) or "black" not in m["colors"] or "white" not in m["colors"]:
            errors.append("%s: colors must have black and white, and only %s" % (where, COLORS))
        if not (0 < m["width"] < 65536 and 0 < m["height"] < 65536):
            errors.append("%s: bad screen size" % where)
        if not 0 <= m["mac_code"] <= 255:
            errors.append("%s: mac_code is one byte" % where)
        if "photo" in m and not os.path.exists(os.path.join(ROOT, "web", m["photo"].get("file", ""))):
            errors.append("%s: photo %s is not in web/" % (where, m["photo"].get("file")))
        if m["chip"] == "zbs243" and m["height"] > 248:
            # tag/src/model.h: a column is indexed with uint8_t, and the layout format has u8 Y/H
            errors.append("%s: the ZBS243 firmware draws at most 248 pixels high (needs layout format 2)" % where)
        if "red" in m["colors"] or "yellow" in m["colors"]:
            errors.append("%s: the firmware does not draw red or yellow yet (plan-flere-tagtyper 2b)" % where)
        layout = os.path.join(ROOT, "tag", "designs", "layouts", m["name"] + ".json")
        if not os.path.exists(layout):
            errors.append("%s: no example layout file %s (the simulator and web page use it)" %
                          (where, os.path.relpath(layout, ROOT)))
    if errors:
        return errors
    codes = [m["code"] for m in ms]
    if codes != list(range(1, len(ms) + 1)):
        # The AP keeps tables indexed by code - 1, and 0 is "unknown" in POLL
        errors.append("codes must be 1, 2, 3, ... without gaps (they are %s)" % codes)
    for f in ("build", "name", "id"):
        vals = [m[f] for m in ms]
        if len(set(vals)) != len(vals):
            errors.append("two models have the same %s" % f)
    if len({m["mac_code"] for m in ms}) != len(ms):
        errors.append("two models have the same mac_code")
    return errors


def c_str(s):
    return json.dumps(s)


def gen_shared_h(ms):
    out = ["/* %s */" % HEADER,
           "#ifndef ESL_MODELS_GEN_H",
           "#define ESL_MODELS_GEN_H",
           "",
           "/* Model byte in POLL (requirement T18); 0 = ESL_MODEL_UNKNOWN (older firmware). */"]
    for m in ms:
        out.append("#define ESL_MODEL_%-8s %d   /* %s (%s) */" % (m["build"], m["code"], m["label"], m["product"]))
    out += ["",
            "/* Codes run 1 .. ESL_MODEL_COUNT - 1; tables indexed by code - 1 have ESL_MODEL_COUNT - 1 rows. */",
            "#define ESL_MODEL_COUNT    %d" % (len(ms) + 1),
            "",
            "/* Screen size per model (= DRAW_W/DRAW_H on the tag) */"]
    for m in ms:
        out.append("#define ESL_MODEL_%s_W %d" % (m["build"], m["width"]))
        out.append("#define ESL_MODEL_%s_H %d" % (m["build"], m["height"]))
    out += ["",
            "/* X(code, name in the API, id, width, height, has_red) for each model, in code order */",
            "#define ESL_MODEL_LIST(X) \\"]
    for m in ms:
        out.append("    X(%d, %s, %s, %d, %d, %d) \\" % (m["code"], c_str(m["name"]), c_str(m["id"]), m["width"],
                                                     m["height"], int(m["has_red"])))
    out += ["", "#endif", ""]
    return "\n".join(out)


def gen_tag_h(ms):
    out = ["/* %s */" % HEADER,
           "/* Selected with -DMODEL=<build> (tag/tools/build.py MODEL=...); included by model.h. */",
           "#ifndef MODEL_GEN_H",
           "#define MODEL_GEN_H",
           "",
           "#ifndef MODEL",
           "#define MODEL %s" % ms[0]["build"],
           "#endif",
           ""]
    for i, m in enumerate(ms):
        out += ["%s MODEL == %s" % ("#if" if i == 0 else "#elif", m["build"]),
                "/* %s (%s) */" % (m["label"], m["product"]),
                "#define MODEL_CODE       %d" % m["code"],
                "#define MODEL_NAME       %s" % c_str(m["name"]),
                "#define MODEL_HAS_RED    %d" % int(m["has_red"]),
                "#define DRAW_W           %d" % m["width"],
                "#define DRAW_H           %d" % m["height"],
                "/* the same model in shared/models_gen.h, for the checks in proto.c and layout.c */",
                "#define MODEL_ESL_CODE   ESL_MODEL_%s" % m["build"],
                "#define MODEL_ESL_W      ESL_MODEL_%s_W" % m["build"],
                "#define MODEL_ESL_H      ESL_MODEL_%s_H" % m["build"]]
    out += ["#else",
            "#error \"unknown MODEL (shared/models.json has %s)\"" % ", ".join(m["build"] for m in ms),
            "#endif",
            "",
            "#endif",
            ""]
    return "\n".join(out)


def gen_js(ms):
    out = ["// %s" % HEADER,
           "//",
           "// The tag models, keyed by the name the AP's API uses (\"2.9\", \"1.54\").",
           "//   code      model byte in POLL and in tag firmware images",
           "//   build     -DMODEL=<build>; the renderer is wasm/render-<build>.js, the firmware tag-<build>.bin",
           "//   macCode   byte 6 of the MAC on a tag of this model",
           "//   photo     a picture of the tag under web/ for the flasher's model picker, or null",
           "",
           "export const MODELS = {"]
    for m in ms:
        out.append("  %s: {" % c_str(m["name"]))
        out.append("    code: %d, build: %s, id: %s, label: %s, product: %s," % (
            m["code"], c_str(m["build"]), c_str(m["id"]), c_str(m["label"]), c_str(m["product"])))
        out.append("    width: %d, height: %d, colors: %s, macCode: 0x%02x, status: %s," % (
            m["width"], m["height"], json.dumps(m["colors"]), m["mac_code"], c_str(m["status"])))
        p = m.get("photo")
        out.append("    photo: %s," % ("{ file: %s, width: %d, height: %d }" % (c_str(p["file"]), p["width"], p["height"])
                                       if p else "null"))
        out.append("  },")
    out += ["};",
            "",
            "// Name in the API by model code, e.g. MODEL_BY_CODE[2] === \"1.54\"",
            "export const MODEL_BY_CODE = Object.fromEntries(Object.entries(MODELS).map(([n, m]) => [m.code, n]));",
            ""]
    return "\n".join(out)


def gen_client_block(ms):
    names = ", ".join(c_str(m["name"]) for m in ms)
    return "\n".join([
        "# BEGIN models (%s)" % HEADER,
        "MODELS = (%s%s)" % (names, "," if len(ms) == 1 else ""),
        "MODEL_BY_CODE = {%s}" % ", ".join("%d: %s" % (m["code"], c_str(m["name"])) for m in ms),
        "# Model code in byte 6 of the MAC",
        "MODEL_MAC_CODE = {%s}" % ", ".join("%s: 0x%02X" % (c_str(m["name"]), m["mac_code"]) for m in ms),
        "# END models",
    ])


BLOCK = re.compile(r"# BEGIN models \(.*?\n# END models", re.S)


def outputs(ms):
    client = os.path.join(ROOT, "tools", "esl-client", "esl_client.py")
    with open(client, encoding="utf-8") as f:
        text = f.read()
    if not BLOCK.search(text):
        sys.exit("%s has no \"# BEGIN models\" ... \"# END models\" block" % client)
    return {
        os.path.join(ROOT, "shared", "models_gen.h"): gen_shared_h(ms),
        os.path.join(ROOT, "tag", "src", "model_gen.h"): gen_tag_h(ms),
        os.path.join(ROOT, "web", "js", "models.js"): gen_js(ms),
        client: BLOCK.sub(lambda _: gen_client_block(ms), text, count=1),
    }


def main():
    check = "--check" in sys.argv[1:]
    with open(models.PATH, encoding="utf-8") as f:
        raw = json.load(f)["models"]
    errors = validate([dict(m, mac_code=int(m["mac_code"], 16)) if "mac_code" in m else m for m in raw])
    if errors:
        sys.exit("shared/models.json:\n  " + "\n  ".join(errors))
    stale = []
    for path, text in outputs(models.load()).items():
        old = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as f:
                old = f.read()
        if old == text:
            continue
        rel = os.path.relpath(path, ROOT)
        if check:
            stale.append(rel)
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
            print("wrote", rel)
    if stale:
        sys.exit("not up to date with shared/models.json (run python tools/gen_models.py): " + ", ".join(stale))
    if check:
        print("generated model files are up to date")


if __name__ == "__main__":
    main()
